#!/usr/bin/env node
// Generates everything that follows from the Foundry contract, one OpenAPI 3.1 document in
// several source files under contracts/:
//   - Redocly bundles contracts/foundry.openapi.yaml with every component of
//     contracts/models/*.yaml and lints it (contracts/redocly.yaml);
//   - openapi-typescript generates the TS types from the bundle (packages/protocol/src/contract.gen.ts);
//   - the bundle's components become the JSON Schema 2020-12 document both validators load
//     (Ajv in TS, santhosh-tekuri/jsonschema v6 in Go);
//   - oapi-codegen generates the Go models of each source file (contracts/oapi-codegen/<package>.yaml).
// The code here is glue only: it adds what the generators need (x-order, the jsonempty
// collection types, the oasdiff operations of x-stored schemas) and formats the output.
//
//   node scripts/generate-contracts.mjs                 write the generated files
//   node scripts/generate-contracts.mjs --check         fail on a stale file or a breaking change
//   node scripts/generate-contracts.mjs --check --base <git rev>
// Either way a Redocly lint problem fails the run.
//
// The breaking-change check (oasdiff) compares the x-stored schemas, which old rows still hold,
// with the contract at the merge base of HEAD and origin/main (or HEAD). Acknowledge an
// intended break in contracts/oasdiff-err-ignore.txt.
import { execFileSync, spawnSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import prettier from "prettier";
import ts from "typescript";

const root = resolve(import.meta.dirname, "..");
const fromProtocol = createRequire(
  resolve(root, "packages/protocol/package.json"),
);
const { parse, stringify } = fromProtocol("yaml");
const openapiTS = fromProtocol("openapi-typescript");
const redocly = fromProtocol("@redocly/openapi-core");

// Pinned Go tools, each in its own module under contracts/tools so neither moves the other's
// dependencies (or the server's).
const goTool = (name, toolArgs) =>
  spawnSync(
    "go",
    ["-C", resolve(root, "contracts/tools", name), "tool", name, ...toolArgs],
    { encoding: "utf8", maxBuffer: 64 << 20 },
  );
const goModuleVersion = (tool, module) =>
  readFileSync(resolve(root, "contracts/tools", tool, "go.mod"), "utf8").match(
    new RegExp(`${module} (v\\S+)`),
  )[1];
const versions = {
  "openapi-typescript": fromProtocol("openapi-typescript/package.json").version,
  "oapi-codegen": goModuleVersion(
    "oapi-codegen",
    "github.com/oapi-codegen/oapi-codegen/v2",
  ),
};

// Each Go package: the source directory under contracts/ and its oapi-codegen configuration.
// A source file <name>.yaml becomes <output>/<name>_gen.go.
const goTargets = [
  {
    sources: "models",
    config: "contracts/oapi-codegen/store.yaml",
    output: "apps/server/internal/store",
  },
];
const jsonEmpty =
  "github.com/foundry-dev/foundry/apps/server/internal/jsonempty";

const args = process.argv.slice(2);
const check = args.includes("--check");
const base = args.includes("--base") ? args[args.indexOf("--base") + 1] : "";
const refName = (ref) => ref.slice(ref.lastIndexOf("/") + 1);
const banner = (source, tool) =>
  `Code generated by scripts/generate-contracts.mjs from ${source} (${tool}); DO NOT EDIT.`;
const redoclyConfig = await redocly.loadConfig({
  configPath: resolve(root, "contracts/redocly.yaml"),
});

// The source files of a checkout and the bundled document. The root gets every component of
// every source file; Redocly resolves the rest.
async function loadContract(dir) {
  const rootPath = join(dir, "contracts/foundry.openapi.yaml");
  const rootDoc = parse(readFileSync(rootPath, "utf8"));
  const schemas = {};
  const files = {};
  for (const target of goTargets) {
    const sourceDir = join(dir, "contracts", target.sources);
    for (const file of readdirSync(sourceDir)
      .filter((f) => f.endsWith(".yaml"))
      .sort()) {
      const path = `${target.sources}/${file}`;
      files[path] = parse(readFileSync(join(sourceDir, file), "utf8"));
      for (const name of Object.keys(files[path].components?.schemas ?? {})) {
        if (schemas[name])
          throw new Error(`Schema ${name} is defined twice (${path})`);
        schemas[name] = { $ref: `./${path}#/components/schemas/${name}` };
      }
    }
  }
  const source = stringify({
    ...rootDoc,
    components: { ...rootDoc.components, schemas },
  });
  const problems = await redocly.lintFromString({
    source,
    absoluteRef: rootPath,
    config: redoclyConfig,
  });
  const { bundle } = await redocly.bundleFromString({
    source,
    absoluteRef: rootPath,
    config: redoclyConfig,
  });
  const bundled = bundle.parsed;
  // Redocly names a component it pulls in after the last segment of its pointer; every
  // schema must keep the name it was written with.
  const names = Object.keys(bundled.components?.schemas ?? {});
  if (names.join() !== Object.keys(schemas).join())
    problems.push({
      message: `bundled schema names differ from the sources: ${names.filter((n) => !schemas[n]).join(", ")}`,
    });
  if (problems.length)
    throw new Error(
      `${rootPath}: ${problems.length} problem(s):\n` +
        problems
          .map(
            (p) =>
              `  ${p.ruleId ?? "bundle"}: ${p.message} (${p.location?.[0]?.source?.absoluteRef ?? ""}${p.location?.[0]?.pointer ?? ""})`,
          )
          .join("\n"),
    );
  return { files, bundled };
}

async function format(text, path) {
  const options = await prettier.resolveConfig(resolve(root, path));
  return prettier.format(text, { ...options, filepath: path });
}

// TS: openapi-typescript with one exported alias per schema (`export type IssueContract = ...`);
// `components` stays module-private.
async function typescript(doc) {
  // The recursive JSONValue is one named alias: openapi-typescript's inline form
  // `components["schemas"]["JSONValue"][]` is rejected by tsc (TS2502).
  const jsonValue =
    "null | boolean | number | string | JSONValue[] | { [key: string]: JSONValue }";
  const ast = await openapiTS.default(structuredClone(doc), {
    transform(_schema, options) {
      if (options.path === "#/components/schemas/JSONValue")
        return ts.factory.createTypeReferenceNode("JSONValue");
    },
  });
  const components = ast.find(
    (node) =>
      ts.isInterfaceDeclaration(node) && node.name.text === "components",
  );
  const aliases = Object.keys(doc.components.schemas)
    .map(
      (name) =>
        `export type ${name} = ${name === "JSONValue" ? jsonValue : `components["schemas"]["${name}"]`};`,
    )
    .join("\n");
  return format(
    `// ${banner("contracts/", `openapi-typescript ${versions["openapi-typescript"]}`)}\n` +
      openapiTS
        .astToString([components])
        .replace(/^export interface components/m, "interface components") +
      aliases +
      "\n",
    "packages/protocol/src/contract.gen.ts",
  );
}

// JSON Schema 2020-12: the components as $defs, without OpenAPI-only keywords (x-*, the
// numeric `format` registry, discriminator mappings, which Ajv rejects).
async function jsonSchema(doc) {
  const oasFormats = new Set(["int32", "int64", "float", "double"]);
  const convert = (value) => {
    if (Array.isArray(value)) return value.map(convert);
    if (!value || typeof value !== "object") return value;
    return Object.fromEntries(
      Object.entries(value)
        .filter(([key]) => !key.startsWith("x-"))
        .filter(([key, v]) => !(key === "format" && oasFormats.has(v)))
        .map(([key, v]) =>
          key === "$ref"
            ? [key, `#/$defs/${refName(v)}`]
            : key === "discriminator"
              ? [key, { propertyName: v.propertyName }]
              : [key, convert(v)],
        ),
    );
  };
  return format(
    JSON.stringify({
      $comment: banner("contracts/", "JSON Schema bundle"),
      $schema: "https://json-schema.org/draft/2020-12/schema",
      $defs: convert(doc.components.schemas),
    }),
    "packages/protocol/src/contract-schema.json",
  );
}

// oapi-codegen's ToCamelCaseWithInitialisms (v2.8.2 initialismsList), for the element type of
// a collection; a wrong name fails to compile.
const initialisms = new Map(
  "ACL API ASCII CPU CSS DNS EOF GUID HTML HTTP HTTPS ID IP JSON QPS RAM RPC SLA SMTP SQL SSH TCP TLS TTL UDP UI GID UID UUID URI URL UTF8 VM XML XMPP XSRF XSS SIP RTP AMQP DB TS"
    .split(" ")
    .map((word) => [word.toLowerCase(), word]),
);
function goType(schema, extraInitialisms) {
  if (schema.$ref) {
    const words = refName(schema.$ref).match(/[A-Z\d]+([a-z\d]+|$)/g);
    return words
      .map(
        (w) =>
          extraInitialisms.get(w.toLowerCase()) ??
          initialisms.get(w.toLowerCase()) ??
          w,
      )
      .join("");
  }
  const scalar = {
    string: "string",
    boolean: "bool",
    integer: { int32: "int32", int64: "int64" }[schema.format] ?? "int",
    number: schema.format === "double" ? "float64" : "float32",
  }[schema.type];
  if (!scalar || schema.enum)
    throw new Error(
      `Name the element schema of a collection: ${JSON.stringify(schema)}`,
    );
  return scalar;
}

// What oapi-codegen needs beyond the contract: x-order keeps declaration order (allOf bases
// first), and a required collection is a jsonempty type so Go encodes nil as [] or {}.
function goDocuments(files, extraInitialisms) {
  const out = structuredClone(files);
  // Schema names are unique across the source files (loadContract checks).
  const schemas = Object.fromEntries(
    Object.values(out).flatMap((doc) =>
      Object.entries(doc.components?.schemas ?? {}),
    ),
  );
  const done = new Set();
  let order = 0;
  const visit = (name) => {
    if (done.has(name)) return;
    done.add(name);
    annotate(schemas[name]);
  };
  const annotate = (schema) => {
    if (!schema || typeof schema !== "object") return;
    for (const part of schema.allOf ?? [])
      part.$ref ? visit(refName(part.$ref)) : annotate(part);
    for (const [key, property] of Object.entries(schema.properties ?? {})) {
      property["x-order"] = ++order;
      const elements =
        property.type === "array"
          ? ["List", property.items]
          : property.type === "object" &&
              !property.properties &&
              typeof property.additionalProperties === "object"
            ? ["Map", property.additionalProperties]
            : undefined;
      if (elements && schema.required?.includes(key)) {
        property["x-go-type"] =
          `jsonempty.${elements[0]}[${goType(elements[1], extraInitialisms)}]`;
        property["x-go-type-import"] = { path: jsonEmpty };
      }
      annotate(property);
    }
    for (const nested of [
      schema.items,
      schema.additionalProperties,
      ...(schema.oneOf ?? []),
    ])
      if (nested && !nested.$ref) annotate(nested);
  };
  Object.keys(schemas).forEach(visit);
  return out;
}

function go(files) {
  const generated = [];
  const dir = mkdtempSync(join(tmpdir(), "fdy-contracts-go-"));
  try {
    for (const target of goTargets) {
      const config = parse(readFileSync(resolve(root, target.config), "utf8"));
      const extra = new Map(
        (config["output-options"]?.["additional-initialisms"] ?? []).map(
          (w) => [w.toLowerCase(), w],
        ),
      );
      const documents = goDocuments(files, extra);
      const sources = Object.keys(documents).filter((f) =>
        f.startsWith(`${target.sources}/`),
      );
      for (const path of sources) {
        mkdirSync(dirname(join(dir, path)), { recursive: true });
        writeFileSync(join(dir, path), stringify(documents[path]));
      }
      for (const path of sources) {
        const name = path.slice(target.sources.length + 1, -".yaml".length);
        const configPath = join(dir, `${name}.config.yaml`);
        // A source file may refine the package's options (`x-oapi-codegen`).
        const own = documents[path]["x-oapi-codegen"] ?? {};
        writeFileSync(
          configPath,
          stringify({
            ...config,
            ...own,
            "output-options": {
              ...config["output-options"],
              ...own["output-options"],
            },
            // The other files of the same directory are the same Go package.
            "import-mapping": Object.fromEntries(
              sources
                .filter((other) => other !== path)
                .map((other) => [
                  `./${other.slice(target.sources.length + 1)}`,
                  "-",
                ]),
            ),
          }),
        );
        const result = goTool("oapi-codegen", [
          "-config",
          configPath,
          join(dir, path),
        ]);
        if (result.status !== 0)
          throw new Error(
            `oapi-codegen failed for contracts/${path}:\n${result.stderr}`,
          );
        const body = result.stdout.slice(
          result.stdout.indexOf(`package ${config.package}`),
        );
        generated.push([
          `${target.output}/${name}_gen.go`,
          execFileSync("gofmt", {
            input: `// ${banner(`contracts/${path}`, `oapi-codegen ${versions["oapi-codegen"]}`)}\n\n${body}`,
            encoding: "utf8",
          }),
        ]);
      }
    }
    return generated;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

// oasdiff only diffs schemas that operations reach. A stored model is both written and read,
// so each x-stored schema gets one synthetic operation with it as request and response.
function withStorageOperations(spec, stored) {
  const copy = structuredClone(spec);
  copy.paths = Object.fromEntries(
    [...stored]
      .filter((name) => copy.components.schemas[name])
      .map((name) => {
        const content = {
          "application/json": {
            schema: { $ref: `#/components/schemas/${name}` },
          },
        };
        return [
          `/x-storage/${name}`,
          {
            post: {
              operationId: `store${name}`,
              requestBody: { required: true, content },
              responses: { 200: { description: "Stored", content } },
            },
          },
        ];
      }),
  );
  return copy;
}
const storedNames = (spec) =>
  Object.entries(spec.components?.schemas ?? {})
    .filter(([, schema]) => schema["x-stored"])
    .map(([name]) => name);

function git(...gitArgs) {
  const result = spawnSync("git", gitArgs, {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 64 << 20,
  });
  return result.status === 0 ? result.stdout.trim() : undefined;
}

// The bundled contract at a git revision; undefined when there is none.
async function contractAt(revision, dir) {
  const paths = git("ls-tree", "-r", "--name-only", revision, "--", "contracts")
    ?.split("\n")
    .filter((path) => path.endsWith(".yaml"));
  if (!paths?.length) return undefined;
  for (const path of paths) {
    mkdirSync(dirname(join(dir, path)), { recursive: true });
    writeFileSync(join(dir, path), git("show", `${revision}:${path}`));
  }
  if (existsSync(join(dir, "contracts/foundry.openapi.yaml")))
    return (await loadContract(dir)).bundled;
  // Before the multi-file layout the contract was this one file.
  return parse(
    readFileSync(join(dir, "contracts/evidence.openapi.yaml"), "utf8"),
  );
}

async function breakingChanges(current) {
  const against =
    base ||
    git("merge-base", "HEAD", "origin/main") ||
    git("rev-parse", "HEAD");
  const dir = mkdtempSync(join(tmpdir(), "fdy-contracts-oasdiff-"));
  try {
    const previous = await contractAt(against, join(dir, "base"));
    if (!previous) {
      console.log(
        `contracts: no contract at ${against}; breaking-change check skipped`,
      );
      return true;
    }
    const stored = new Set([...storedNames(current), ...storedNames(previous)]);
    const write = (name, spec) => {
      writeFileSync(
        join(dir, name),
        stringify(withStorageOperations(spec, stored)),
      );
      return join(dir, name);
    };
    const result = goTool("oasdiff", [
      "breaking",
      write("base.yaml", previous),
      write("revision.yaml", current),
      "--severity-levels",
      resolve(root, "contracts/oasdiff-severity.txt"),
      "--err-ignore",
      resolve(root, "contracts/oasdiff-err-ignore.txt"),
      "--flatten-allof",
      "--fail-on",
      "ERR",
      "--color",
      "never",
    ]);
    if (result.status !== 0) {
      console.error(
        `contracts: breaking changes to x-stored schemas against ${against} (acknowledge intended ones in contracts/oasdiff-err-ignore.txt):\n${result.stdout}${result.stderr}`,
      );
      return false;
    }
    console.log(
      `contracts: no breaking changes to ${stored.size} x-stored schemas against ${against}`,
    );
    return true;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const { files, bundled } = await loadContract(root);
const schemaJSON = await jsonSchema(bundled);
const outputs = [
  ["packages/protocol/src/contract.gen.ts", await typescript(bundled)],
  ["packages/protocol/src/contract-schema.json", schemaJSON],
  ["apps/server/internal/store/contract-schema.json", schemaJSON],
  ...go(files),
];
let ok = true;
for (const [name, content] of outputs) {
  const path = resolve(root, name);
  if (!check) writeFileSync(path, content);
  else if (!existsSync(path) || readFileSync(path, "utf8") !== content) {
    console.error(
      `Stale generated file: ${name} (run pnpm generate:contracts)`,
    );
    ok = false;
  }
}
if (check) ok = (await breakingChanges(bundled)) && ok;
if (!ok) process.exit(1);
